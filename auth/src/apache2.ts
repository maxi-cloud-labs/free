function macroModule(name: string, elModule, elModule2, grantLocal: boolean, elLocalRanges, ipExternal: string): string {
	const path = has(elModule, "path") ? elModule.path : "/usr/local/modules/" + name;
	let m = "<Macro Macro_" + name + ">\n\tAppModuleName " + name + "\n\tUse Macro_Redirect " + name + "\n";
	const elEnabled = has(elModule2, "enabled") ? elModule2.enabled : elModule.enabled;
	const ready = !has(elModule, "setup") || has(elModule2, "setupDone");
	if (elEnabled === true && ready) {
		const elPermissions = has(elModule2, "permissions") ? elModule2.permissions : elModule.permissions;
		if (has(elModule, "addConfigBegin"))
			m += "\t" + elModule.addConfigBegin + "\n";
		if (has(elModule2, "addConfigBegin"))
			m += "\t" + elModule2.addConfigBegin + "\n";

		let doDirectory = true;
		if (has(elModule, "reverseProxy")) {
			for (const elReverseProxy of children(elModule.reverseProxy)) {
				const type_ = elReverseProxy?.type;
				const path_ = elReverseProxy?.path;
				const path2_ = typeof elReverseProxy?.path2 === "string" ? elReverseProxy.path2 : path_;
				const reversePort = num(elReverseProxy?.port);
				const localhost = has(elModule, "containerized") ? "169.254.10." + num(elModule.containerID) : "localhost";
				if (type_ === "http") {
					m += "\tProxyPass " + path_ + " http://" + localhost + ":" + reversePort + path2_ + "\n";
					m += "\tProxyPassReverse " + path_ + " http://" + localhost + ":" + reversePort + path2_ + "\n";
					if (path_ === "/")
						doDirectory = false;
				} else if (type_ === "ws") {
					m += "\tRewriteCond %{HTTP:Upgrade} websocket [NC]\n\tRewriteCond %{HTTP:Connection} upgrade [NC]\n";
					m += "\tRewriteRule ^" + path_ + "(.*) ws://" + localhost + ":" + reversePort + path_ + "$1 [P,L]\n";
				}
			}
			m += "\t<Proxy *>\n" + writePermissions(elPermissions, grantLocal, elLocalRanges, ipExternal) + "\t</Proxy>\n";
		}
		if (doDirectory) {
			m += "\tDocumentRoot " + path + "\n\t<Directory " + path + ">\n";
			if (has(elModule, "addLineInDirectory"))
				m += "\t\t" + elModule.addLineInDirectory + "\n";
			if (has(elModule2, "addLineInDirectory"))
				m += "\t\t" + elModule2.addLineInDirectory + "\n";
			m += writePermissions(elPermissions, grantLocal, elLocalRanges, ipExternal);
			if (has(elModule2, "directoryIndex"))
				m += "\t\tDirectoryIndex " + elModule2.directoryIndex + "\n";
			else if (has(elModule, "directoryIndex"))
				m += "\t\tDirectoryIndex " + elModule.directoryIndex + "\n";
			for (const [key, option] of [["followSymLinks", "FollowSymLinks"], ["multiViews", "MultiViews"], ["indexes", "Indexes"]]) {
				if (has(elModule2, key))
					m += writeOption(option, elModule2[key] === true);
				else if (has(elModule, key))
					m += writeOption(option, elModule[key] === true);
			}
			m += "\t</Directory>\n";
		}

		if (has(elModule, "addConfigEnd"))
			m += "\t" + elModule.addConfigEnd + "\n";
		if (has(elModule2, "addConfigEnd"))
			m += "\t" + elModule2.addConfigEnd + "\n";

		if (name === "apache2" || name === "_core_")
			m += "\tUse Macro_Rewrite\n";
		if (has(elModule, "autoLoginNoGzip")) {
			for (const al of children(elModule.autoLoginNoGzip))
				m += "\tSetEnvIf Request_URI " + al + " no_gzip\n";
			m += "\tRequestHeader unset Accept-Encoding env=no_gzip\n";
		}
	} else {
		m += "\tRewriteCond %{REQUEST_URI} !^/_app_/disabled.php$\n";
		m += "\tRewriteRule ^/.*$ /_app_/disabled.php?m=" + name + (!ready ? "&notSetup" : "") + " [PT,L]\n";
	}
	m += "\tCustomLog /var/log/apache2/module-" + name + ".log combined\n";
	return m + "</Macro>\n";
}

export function buildApache2Conf(cloud, modulesDefault, modules, fqdn: string[], ipExternal: string) {
	const ap = modulesDefault?.apache2;
	const grantLocal = cloud?.security?.grantLocalPermission === true;
	const elLocalRanges = ap?.localRanges;
	let p = "<IfModule ssl_module>\n\tListen 443\n</IfModule>\n";
	let m = header(cloud);
	m += "<Macro Macro_Rewrite>\n";
	for (const [name, elModule] of Object.entries<any>(modulesDefault ?? {}))
		if (has(elModule, "web"))
			m += rewrite(name, elModule, modules?.[name], num(elModule.localPort));
	m += "\tRewriteCond %{HTTP_HOST} ^(app\\.|www\\.)?(.*)\n\tRewriteRule ^/m/([^/]+)(.*) %{REQUEST_SCHEME}://$1.%2$2 [NC,L]\n</Macro>\n\n\n";

	// apache2 first, then the other modules in their order (nothing without apache2, as in the C version)
	const names = has(modulesDefault, "apache2") ? ["apache2", ...Object.keys(modulesDefault).filter((n) => n !== "apache2")] : [];
	for (const name of names) {
		const elModule = modulesDefault[name];
		if (!has(elModule, "web"))
			continue;
		const elModule2 = modules?.[name];
		m += macroModule(name, elModule, elModule2, grantLocal, elLocalRanges, ipExternal);

		const localPort = num(elModule.localPort);
		p += "Listen " + localPort + "\n";
		m += "<VirtualHost *:" + localPort + ">\n\tUse Macro_" + name + "\n</VirtualHost>\n";
		m += "<VirtualHost *:80>\n" + fillServer(1, name, elModule, elModule2, fqdn) + "\tUse Macro_" + name + "\n</VirtualHost>\n";
		m += "<IfModule mod_ssl.c>\n\t<VirtualHost *:443>\n" + fillServer(2, name, elModule, elModule2, fqdn);
		m += "\t\tUse Macro_" + name + "\n\t\tUse Macro_SSL\n\t</VirtualHost>\n</IfModule>\n";
		m += "\n\n";
	}
	mkdirSync(apache2Path, { recursive:true });
	writeFileSync(apache2Path + "ports.conf", p, "utf-8");
	writeFileSync(apache2Path + "main.conf", m, "utf-8");
}

export function buildApache2ConfBeforeSetup() {
	mkdirSync(apache2Path, { recursive:true });
	writeFileSync(apache2Path + "ports.conf", "Listen 80\n<IfModule ssl_module>\n\tListen 443\n</IfModule>\n", "utf-8");
	writeFileSync(apache2Path + "main.conf", [
		"<VirtualHost *:80>",
		"\tRewriteEngine on",
		"\tRewriteRule ^(.*)$ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]",
		"</VirtualHost>",
		"<VirtualHost *:443>",
		"\tAlias /_app_ /usr/local/modules/apache2/web",
		"\tRewriteEngine On",
		"\tRewriteCond %{HTTP:Upgrade} websocket [NC]",
		"\tRewriteCond %{HTTP:Connection} upgrade [NC]",
		"\tRewriteRule ^/ws(.*) ws://localhost:8094/ws$1 [P,L]",
		"\tRewriteCond %{REQUEST_URI} !^/_app_ [NC]",
		"\tRewriteRule ^(.*)$ /_app_/setup [R=301,L]",
		"\tRewriteRule ^/_app_/login$ /_app_/setup [R=301,L]",
		"\t<Directory /usr/local/modules/apache2/web>",
		"\t\tRewriteEngine On",
		"\t\tRewriteBase /_app_",
		"\t\tRewriteCond %{REQUEST_FILENAME} !-f",
		"\t\tRewriteCond %{REQUEST_FILENAME} !-d",
		"\t\tRewriteRule . /_app_/index.html [L]",
		"\t\tRequire all granted",
		"\t</Directory>",
		"\tInclude /usr/local/modules/apache2/options-ssl-apache.conf",
		"\tSSLCertificateFile /usr/local/modules/apache2/self-fullchain.pem",
		"\tSSLCertificateKeyFile /usr/local/modules/apache2/self-privkey.pem",
		"</VirtualHost>"
	].join("\n"), "utf-8");
}
